export function createGrid(root) {
  let index = 0;
  for (let i = 0; i < data.length; i++) {
    for (let j = 0; j < data[i].length; j++) {
      // console.log("div");
      index++;
      const cell = document.createElement("DIV");
      if (data[i][j] === 0) {
        cell.classList.add("cell");
      } else {
        cell.classList.add("block", "cell");
      }
      root.append(cell);
    }
  }
  console.log(index, data.length, index / data.length);
}

export function removeActive(grid, className) {
  for (let i = 0; i < grid.length; i++) {
    grid[i].classList.remove(className);
  }
}
